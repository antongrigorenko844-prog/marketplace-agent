'use strict';
const assert=require('node:assert/strict');
const {create}=require('./quote_state.js');
const s=create();
assert.equal(s.canProceed(),false);
assert.throws(()=>s.beginQuote('cartA'));
s.chooseCarrier('ozon');
s.choosePoint('pvz-1');
const old=s.beginQuote('cartA');
s.choosePoint('pvz-2');
assert.equal(s.receiveQuote(old,{available:true,priceRub:200}),false,'Old point response ignored');
const next=s.beginQuote('cartA');
assert.equal(s.receiveQuote(next,{available:true,priceRub:200}),true);
assert.equal(s.snapshot().quote.priceRub,200);
assert.equal(s.canProceed(),false);
s.cartChanged('cartB');
assert.equal(s.snapshot().quote,null,'Cart change invalidates quote');
const third=s.beginQuote('cartB');
assert.equal(s.receiveQuote(third,{available:true,priceRub:-1}),false,'Negative price rejected');
const fourth=s.beginQuote('cartB');
assert.equal(s.receiveQuote(fourth,{available:true,priceRub:0}),true,'Free shipping accepted');
s.chooseCarrier('yandex');
assert.equal(s.snapshot().quote,null);
assert.equal(s.snapshot().carrier,null);
assert.equal(s.receiveQuote(fourth,{available:true,priceRub:100}),false);
assert.equal(s.canProceed(),false);
console.log('PASS: Ozon quote state isolation and stale-response tests');
